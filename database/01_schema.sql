-- Recalculate cached property review score after review changes.
CREATE OR REPLACE FUNCTION refresh_property_review_summary()
RETURNS TRIGGER AS $$
DECLARE
    target_property UUID;
BEGIN
    IF TG_OP = 'DELETE' THEN
        target_property := OLD.property_id;
    ELSE
        target_property := NEW.property_id;
    END IF;
    UPDATE properties p
       SET review_score = COALESCE(s.avg_score, 0),
           review_count = COALESCE(s.review_count, 0),
           updated_at = NOW()
      FROM (
        SELECT property_id, ROUND(AVG(score), 1) AS avg_score, COUNT(*)::INTEGER AS review_count
          FROM reviews
         WHERE property_id = target_property AND status = 'PUBLISHED'
         GROUP BY property_id
      ) s
     WHERE p.id = target_property;

    IF NOT FOUND THEN
        UPDATE properties SET review_score = 0, review_count = 0, updated_at = NOW()
        WHERE id = target_property;
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reviews_refresh_property
AFTER INSERT OR UPDATE OR DELETE ON reviews
FOR EACH ROW EXECUTE FUNCTION refresh_property_review_summary();

