CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1. Accounts managed by Spring Security/JWT (not Supabase Auth).
CREATE TABLE app_users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    phone VARCHAR(30),
    avatar_url VARCHAR(800),
    google_subject VARCHAR(255),
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    role VARCHAR(30) NOT NULL DEFAULT 'CUSTOMER',
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_app_users_role CHECK (role IN ('CUSTOMER', 'HOTEL_MANAGER', 'ADMIN')),
    CONSTRAINT ck_app_users_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'PENDING'))
);
CREATE UNIQUE INDEX uk_app_users_email_lower ON app_users (LOWER(email));
CREATE UNIQUE INDEX uk_app_users_google_subject ON app_users (google_subject) WHERE google_subject IS NOT NULL;
CREATE INDEX idx_app_users_role_status ON app_users (role, status);
CREATE TRIGGER trg_app_users_updated_at
BEFORE UPDATE ON app_users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 2. Accommodation/property master data.
CREATE TABLE properties (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id UUID,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL,
    property_type VARCHAR(40) NOT NULL,
    description TEXT,
    address_line VARCHAR(255) NOT NULL,
    ward VARCHAR(120),
    district VARCHAR(120),
    city VARCHAR(120) NOT NULL,
    province VARCHAR(120),
    country VARCHAR(100) NOT NULL DEFAULT 'Việt Nam',
    postal_code VARCHAR(30),
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    star_rating INTEGER NOT NULL DEFAULT 0,
    review_score NUMERIC(3, 1) NOT NULL DEFAULT 0,
    review_count INTEGER NOT NULL DEFAULT 0,
    check_in_from TIME NOT NULL DEFAULT '14:00',
    check_in_until TIME,
    check_out_from TIME,
    check_out_until TIME NOT NULL DEFAULT '12:00',
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_properties_owner FOREIGN KEY (owner_id) REFERENCES app_users(id) ON DELETE SET NULL,
    CONSTRAINT uk_properties_slug UNIQUE (slug),
    CONSTRAINT ck_properties_type CHECK (property_type IN ('HOTEL', 'APARTMENT', 'RESORT', 'VILLA', 'HOSTEL', 'HOMESTAY')),
    CONSTRAINT ck_properties_stars CHECK (star_rating BETWEEN 0 AND 5),
    CONSTRAINT ck_properties_review_score CHECK (review_score BETWEEN 0 AND 10),
    CONSTRAINT ck_properties_review_count CHECK (review_count >= 0),
    CONSTRAINT ck_properties_status CHECK (status IN ('DRAFT', 'ACTIVE', 'SUSPENDED', 'ARCHIVED'))
);
CREATE INDEX idx_properties_destination ON properties (LOWER(city), LOWER(country), status);
CREATE INDEX idx_properties_name_trgm ON properties USING GIN (LOWER(name) gin_trgm_ops);
CREATE INDEX idx_properties_city_trgm ON properties USING GIN (LOWER(city) gin_trgm_ops);
CREATE INDEX idx_properties_type_stars ON properties (property_type, star_rating, status);
CREATE INDEX idx_properties_featured ON properties (featured, status);
CREATE TRIGGER trg_properties_updated_at
BEFORE UPDATE ON properties FOR EACH ROW EXECUTE FUNCTION set_updated_at();

