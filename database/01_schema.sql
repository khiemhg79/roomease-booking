-- Inventory is room-type level for each stay date.
CREATE TABLE inventory_calendar (
    room_type_id UUID NOT NULL,
    stay_date DATE NOT NULL,
    allotment INTEGER NOT NULL,
    reserved_rooms INTEGER NOT NULL DEFAULT 0,
    stop_sell BOOLEAN NOT NULL DEFAULT FALSE,
    closed_to_arrival BOOLEAN NOT NULL DEFAULT FALSE,
    closed_to_departure BOOLEAN NOT NULL DEFAULT FALSE,
    min_stay INTEGER NOT NULL DEFAULT 1,
    max_stay INTEGER,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (room_type_id, stay_date),
    CONSTRAINT fk_inventory_calendar_room FOREIGN KEY (room_type_id) REFERENCES room_types(id) ON DELETE CASCADE,
    CONSTRAINT ck_inventory_allotment CHECK (allotment >= 0),
    CONSTRAINT ck_inventory_reserved CHECK (reserved_rooms >= 0 AND reserved_rooms <= allotment),
    CONSTRAINT ck_inventory_min_stay CHECK (min_stay > 0),
    CONSTRAINT ck_inventory_max_stay CHECK (max_stay IS NULL OR max_stay >= min_stay)
);
CREATE INDEX idx_inventory_date_room ON inventory_calendar (stay_date, room_type_id);
CREATE INDEX idx_inventory_available ON inventory_calendar (room_type_id, stay_date, stop_sell, reserved_rooms, allotment);
CREATE TRIGGER trg_inventory_calendar_updated_at
BEFORE UPDATE ON inventory_calendar FOR EACH ROW EXECUTE FUNCTION set_updated_at();

